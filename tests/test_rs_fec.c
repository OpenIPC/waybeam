/* Bytewise GF(256) reference, independent of rs_fec.c's tables and NEON
 * path: for symbols past one 1 KB tile, which the vectors above are not. */
static uint8_t ref_mul(uint8_t a, uint8_t b)
{
	uint8_t p = 0;

	while (b) {
		if (b & 1)
			p ^= a;
		a = (uint8_t)((a << 1) ^ (a & 0x80 ? 0x1D : 0));
		b >>= 1;
	}
	return p;
}

static uint8_t ref_inv(uint8_t a)
{
	for (unsigned b = 1; b < 256; b++)
		if (ref_mul(a, (uint8_t)b) == 1)
			return (uint8_t)b;
	return 0;
}

static int test_rs_fec_long_symbols(void)
{
	enum { K = 40, R = 10, LEN = 3782 }; /* 3 full tiles + a 710 B tail */
	static uint8_t src[K][LEN], out[R][LEN], want[LEN];
	int failures = 0;

	for (unsigned i = 0; i < K; i++)
		for (unsigned j = 0; j < LEN; j++)
			src[i][j] = (uint8_t)((i * 131 + j * 7 + (j >> 9)) & 0xFF);
	rs_fec_encode(K, R, src[0], LEN, LEN, out[0], LEN);
	for (unsigned r = 0; r < R; r++) {
		memset(want, 0, sizeof(want));
		for (unsigned i = 0; i < K; i++) {
			const uint8_t c = ref_inv((uint8_t)((K + r) ^ i));

			for (unsigned j = 0; j < LEN; j++)
				want[j] ^= ref_mul(c, src[i][j]);
		}
		CHECK("rs_fec long symbols match the bytewise reference",
			memcmp(out[r], want, LEN) == 0);
	}
	return failures;
}

/* L (protocols/venc-fec.md byte 13, 0x10): exactly one per frame with
 * parity, on the last parity datagram sent; E on the last block's parity. */
static uint8_t g_flags[512]; /* r <= k and k <= 256 sources a frame */
static unsigned g_nflags;

static int keep_flags(const uint8_t *header, size_t header_len,
	const uint8_t *payload1, size_t payload1_len,
	const uint8_t *payload2, size_t payload2_len, void *opaque)
{
	(void)header; (void)header_len; (void)payload1_len;
	(void)payload2; (void)payload2_len; (void)opaque;
	if (g_nflags < sizeof(g_flags))
		g_flags[g_nflags++] = payload1[1];
	return 0;
}

/* One frame through capture and emit on `fec` (its credit carries over):
 * `sources` packets of `len` bytes, packet `big` (if < sources) oversize,
 * which ends capture for the frame (frame = 2). */
static unsigned emit_frame(VencFec *fec, unsigned sources, size_t len, unsigned big)
{
	static uint8_t payload[VENC_FEC_MAX_PAYLOAD_BYTES + 1];
	uint8_t hdr[12] = { 0x80, 96 };
	unsigned i;

	memset(payload, 0x5A, sizeof(payload));
	g_nflags = 0;
	venc_fec_begin_frame(fec);
	for (i = 0; i < sources; i++) {
		hdr[2] = (uint8_t)(i >> 8);
		hdr[3] = (uint8_t)i;
		venc_fec_capture(fec, hdr, payload,
			i == big ? sizeof(payload) : len, NULL, 0);
	}
	venc_fec_emit(fec, keep_flags, NULL);
	return g_nflags;
}

static int test_venc_fec_last_parity(void)
{
	VencFec fec;
	uint32_t x = 12345;
	unsigned f, bad_l = 0, bad_bits = 0, with = 0, multi = 0;
	int failures = 0;

	memset(&fec, 0, sizeof(fec));
	if (venc_fec_set(&fec, 1) != 0)
		return 1;
	/* Varied frames, credit carried: small ones without parity, multi-block
	 * ones, over 256 sources, a last block at r = 0, capture ended early. */
	for (f = 0; f < 2000; f++) {
		unsigned n, i, l = 0, sources;
		size_t len;

		x = x * 1103515245u + 12345u;
		sources = 1 + (x >> 8) % 300;
		len = 1 + (x >> 4) % 1400;
		n = emit_frame(&fec, sources, len, (x & 7) == 0 ? (x >> 16) % sources : sources);
		for (i = 0; i < n; i++) {
			l += (g_flags[i] & 0x10) != 0;
			bad_bits += (g_flags[i] & 0xC7) != 0x01;
		}
		bad_l += n ? !(l == 1 && (g_flags[n - 1] & 0x10)) : l != 0;
		with += n > 0;
		multi += sources > VENC_FEC_BLOCK_MAX && n > 0;
	}
	venc_fec_free(&fec);
	CHECK("venc_fec: L on exactly the last parity datagram of each frame", bad_l == 0);
	CHECK("venc_fec: detection bits kept with L", bad_bits == 0);
	CHECK("venc_fec: the run covered frames with and without parity", with > 100 && with < 2000);
	CHECK("venc_fec: the run covered multi-block frames", multi > 100);
	return failures;
}

int test_rs_fec(void)
{
	static uint8_t sym[26][2 + 40];
	static uint8_t out[26][2 + 40];
	int failures = 0;
	size_t c;

	for (c = 0; c < sizeof(g_cases) / sizeof(g_cases[0]); c++) {
		unsigned i, j, maxlen = 0;

		for (i = 0; i < g_cases[c].k; i++)
			if (g_cases[c].len[i] > maxlen)
				maxlen = g_cases[c].len[i];
		memset(sym, 0, sizeof(sym));
		for (i = 0; i < g_cases[c].k; i++) {
			sym[i][0] = (uint8_t)(g_cases[c].len[i] >> 8);
			sym[i][1] = (uint8_t)g_cases[c].len[i];
			for (j = 0; j < g_cases[c].len[i]; j++)
				sym[i][2 + j] = (uint8_t)((i * 37 + j * 11 + 5) & 0xFF);
		}
		rs_fec_encode(g_cases[c].k, g_cases[c].r, sym[0], sizeof(sym[0]),
			2 + maxlen, out[0], sizeof(out[0]));
		for (j = 0; j < g_cases[c].r; j++)
			CHECK("rs_fec matches the waybeam-link vector",
				memcmp(out[j], g_cases[c].par[j], 2 + maxlen) == 0);
	}
	failures += test_rs_fec_long_symbols();
	failures += test_venc_fec_last_parity();
	return failures;
}
